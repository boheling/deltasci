"""Biomed notebook scaffold.

Discipline (v0.3.1):
- **Real working code** for canonical workflow steps where AI is well-covered:
  scRNA-seq QC, normalization, dimensionality reduction, clustering, marker
  scoring, spatial-neighbor graphs, sklearn evaluation. These are textbook
  patterns; every scanpy tutorial implements them identically.
- **TODO markers** only for substantive customizations the AI cannot reliably
  produce: your specific marker panel for cell typing, your specific model
  architecture, your specific threshold values.

Step-name keyword detection routes each protocol step to a step-specific code
emitter. Steps whose names don't match any known canonical pattern fall back
to a generic stub.
"""

from __future__ import annotations

from deltasci.hypothesis import GroundedHypothesis
from deltasci.notebook.cells import code_cell, markdown_cell
from deltasci.protocol import ExperimentPlan, ProtocolStep


def build_cells(hypothesis: GroundedHypothesis, plan: ExperimentPlan) -> list[dict]:
    cells: list[dict] = []

    cells.append(markdown_cell(
        f"# {hypothesis.title}\n"
        f"\n_Notebook scaffold generated by deltasci. Canonical workflow code is real; "
        f"`# TODO` markers indicate where substantive customization is required._\n"
        f"_See `README.md` for orientation._\n"
    ))

    cells.append(markdown_cell(
        "## Hypothesis\n\n"
        f"{hypothesis.statement}\n\n"
        "### Falsifiability\n"
        f"- **Prediction:** {hypothesis.falsifiability.prediction}\n"
        f"- **Threshold:** {hypothesis.falsifiability.threshold}\n"
        f"- **Null outcome:** {hypothesis.falsifiability.null_outcome}\n"
    ))

    cells.append(code_cell(_imports_cell()))
    cells.append(markdown_cell(_data_acquisition_md(plan)))
    cells.append(code_cell(_data_acquisition_code(plan)))

    for step in plan.steps:
        cells.append(_step_markdown(step))
        cells.append(code_cell(_route_step_code(step)))

    cells.append(markdown_cell("## Falsifiability check\n"))
    cells.append(code_cell(_falsifiability_code(plan)))

    cells.append(markdown_cell(
        "## Notes\n\n"
        "When you've filled in the TODOs and the falsifiability check passes:\n\n"
        "1. Re-audit with `deltasci audit <run-dir> --write` so the citation audit\n"
        "   reflects any new datasets or references you wired in.\n"
        "2. Consider archiving and starting a fresh deltasci pass with `deltasci run\n"
        "   --iterate-on <this-run-dir>` so the iteration history captures the change.\n"
    ))

    return cells


