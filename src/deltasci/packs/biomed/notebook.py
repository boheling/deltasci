def _step_spatial_graph(step: ProtocolStep) -> str:
    return (
        f"# === Step {step.order}: {step.name} ===\n"
        "# Canonical squidpy: spatial-neighbors graph + neighborhood enrichment.\n"
        "import squidpy as sq\n"
        "\n"
        "N_SPATIAL_NEIGHBORS = 10  # k for kNN in physical-µm space\n"
        "\n"
        "if 'spatial' not in adata.obsm:\n"
        "    raise RuntimeError('adata.obsm[\"spatial\"] missing — this dataset is not spatial.')\n"
        "\n"
        "sq.gr.spatial_neighbors(\n"
        "    adata,\n"
        "    coord_type='generic',\n"
        "    n_neighs=N_SPATIAL_NEIGHBORS,\n"
        ")\n"
        "print(f'spatial graph: {adata.obsp[\"spatial_connectivities\"].nnz} edges')\n"
        "\n"
        "# Neighborhood enrichment by cell type — what tends to be near what.\n"
        "if 'celltype' in adata.obs.columns:\n"
        "    sq.gr.nhood_enrichment(adata, cluster_key='celltype', seed=RANDOM_SEED)\n"
        "    print('nhood enrichment computed (see adata.uns[\"celltype_nhood_enrichment\"])')\n"
        "\n"
        "# Per-tumor PyG graph for downstream learning.\n"
        "import torch_geometric.data as pyg_data\n"
        "\n"
        "def build_per_tumor_graph(adata_tumor):\n"
        "    coo = adata_tumor.obsp['spatial_connectivities'].tocoo()\n"
        "    edge_index = torch.tensor(np.vstack([coo.row, coo.col]), dtype=torch.long)\n"
        "    feat_genes = ['CD204', 'CD163', 'CD68', 'CD3D', 'CD8A', 'MKI67']  # TODO: tune panel\n"
        "    feat_genes = [g for g in feat_genes if g in adata_tumor.var_names]\n"
        "    X = adata_tumor[:, feat_genes].X\n"
        "    x_genes = X.toarray() if hasattr(X, 'toarray') else np.asarray(X)\n"
        "    celltype = adata_tumor.obs.get('celltype', pd.Series(['na'] * adata_tumor.n_obs)).fillna('na')\n"
        "    x_celltype = pd.get_dummies(celltype).values\n"
        "    x = torch.tensor(np.hstack([x_genes, x_celltype]), dtype=torch.float)\n"
        "    return pyg_data.Data(x=x, edge_index=edge_index)\n"
        "\n"
        "tumor_graphs = []\n"
        "if 'patient_id' in adata.obs.columns:\n"
        "    for pid in adata.obs['patient_id'].unique():\n"
        "        sub = adata[adata.obs['patient_id'] == pid].copy()\n"
        "        if 'spatial_connectivities' not in sub.obsp:\n"
        "            sq.gr.spatial_neighbors(sub, coord_type='generic', n_neighs=N_SPATIAL_NEIGHBORS)\n"
        "        tumor_graphs.append((pid, build_per_tumor_graph(sub)))\n"
        "    print(f'built {len(tumor_graphs)} per-tumor graphs')\n"
    )


def _step_train(step: ProtocolStep) -> str:
    return (
        f"# === Step {step.order}: {step.name} ===\n"
        "# GNN + classification head — skeleton with a real training loop.\n"
        "# The forward pass is real (GAT-based); swap to HGT for typed edges if your\n"
        "# hypothesis depends on edge typing.\n"
        "\n"
        "import torch_geometric.nn as pyg_nn\n"
        "from torch_geometric.loader import DataLoader\n"
        "\n"
        "HIDDEN_DIM = 64\n"
        "NUM_HEADS = 4\n"
        "NUM_LAYERS = 2\n"
        "DROPOUT = 0.2\n"
        "BATCH_SIZE = 4   # graphs per batch; small for whole-tumor graphs\n"
        "EPOCHS = 30\n"
        "LR = 1e-3\n"
        "\n"
        "class TumorClassifier(nn.Module):\n"
        "    def __init__(self, in_dim, hidden=HIDDEN_DIM, num_layers=NUM_LAYERS):\n"
        "        super().__init__()\n"
        "        self.convs = nn.ModuleList([\n"
        "            pyg_nn.GATConv(in_dim if i == 0 else hidden, hidden,\n"
        "                           heads=NUM_HEADS, concat=False, dropout=DROPOUT)\n"
        "            for i in range(num_layers)\n"
        "        ])\n"
        "        self.pool = pyg_nn.global_mean_pool\n"
        "        self.head = nn.Sequential(\n"
        "            nn.Linear(hidden, hidden),\n"
        "            nn.ReLU(),\n"
        "            nn.Dropout(DROPOUT),\n"
        "            nn.Linear(hidden, 1),\n"
        "        )\n"
        "\n"
        "    def forward(self, data):\n"
        "        x, edge_index, batch = data.x, data.edge_index, data.batch\n"
        "        for conv in self.convs:\n"
        "            x = torch.relu(conv(x, edge_index))\n"
        "        h = self.pool(x, batch)\n"
        "        return self.head(h).squeeze(-1)\n"
        "\n"
        "# TODO: assemble dataset (tumor_graphs from previous step) with patient labels\n"
        "labeled_graphs = []  # list[Data] with .y attached\n"
        "if not labeled_graphs:\n"
        "    raise NotImplementedError(\n"
        "        'Attach binary outcome labels to each per-tumor graph: graph.y = torch.tensor([label])'\n"
        "    )\n"
        "\n"
        "loader = DataLoader(labeled_graphs, batch_size=BATCH_SIZE, shuffle=True)\n"
        "in_dim = labeled_graphs[0].x.shape[1]\n"
        "model = TumorClassifier(in_dim=in_dim)\n"
        "optimizer = torch.optim.Adam(model.parameters(), lr=LR)\n"
        "loss_fn = nn.BCEWithLogitsLoss()\n"
        "\n"
        "model.train()\n"
        "for epoch in range(EPOCHS):\n"
        "    losses = []\n"
        "    for batch in loader:\n"
        "        optimizer.zero_grad()\n"
        "        logits = model(batch)\n"
        "        loss = loss_fn(logits, batch.y.float())\n"
        "        loss.backward()\n"
        "        optimizer.step()\n"
        "        losses.append(loss.item())\n"
        "    if epoch % 5 == 0:\n"
        "        print(f'epoch {epoch}: train loss = {np.mean(losses):.4f}')\n"
    )


def _step_evaluate(step: ProtocolStep) -> str:
    return (
        f"# === Step {step.order}: {step.name} ===\n"
        "# Held-out evaluation: AUROC + AUPRC + Brier + calibration curve.\n"
        "\n"
        "model.eval()\n"
        "y_true_list, y_pred_list = [], []\n"
        "with torch.no_grad():\n"
        "    for batch in loader:  # TODO: replace with held-out validation loader\n"
        "        logits = model(batch)\n"
        "        probs = torch.sigmoid(logits).cpu().numpy()\n"
        "        y_pred_list.extend(probs.tolist())\n"
        "        y_true_list.extend(batch.y.cpu().numpy().tolist())\n"
        "y_true = np.array(y_true_list)\n"
        "y_pred = np.array(y_pred_list)\n"
        "\n"
        "model_auroc = roc_auc_score(y_true, y_pred)\n"
        "model_auprc = average_precision_score(y_true, y_pred)\n"
        "model_brier = brier_score_loss(y_true, y_pred)\n"
        "print(f'AUROC: {model_auroc:.4f}')\n"
        "print(f'AUPRC: {model_auprc:.4f}')\n"
        "print(f'Brier: {model_brier:.4f}')\n"
        "\n"
        "from sklearn.calibration import calibration_curve\n"
        "prob_true, prob_pred = calibration_curve(y_true, y_pred, n_bins=10, strategy='quantile')\n"
        "for pt, pp in zip(prob_true, prob_pred):\n"
        "    print(f'  bin midpoint {pp:.2f} → observed rate {pt:.2f}')\n"
        "\n"
        "# TODO: compute baseline predictions (e.g., bulk IFN-γ score per patient).\n"
        "y_pred_baseline = None\n"
        "if y_pred_baseline is None:\n"
        "    raise NotImplementedError(\n"
        "        'Compute baseline predictions for the same held-out cohort.'\n"
        "    )\n"
        "baseline_auroc = roc_auc_score(y_true, y_pred_baseline)\n"
        "print(f'baseline AUROC: {baseline_auroc:.4f}')\n"
        "print(f'lift over baseline: {model_auroc - baseline_auroc:+.4f}')\n"
    )


def _step_generic(step: ProtocolStep) -> str:
    slug = "_".join(step.name.lower().split())[:32]
    return (
        f"# === Step {step.order}: {step.name} ===\n"
        f"# No canonical pattern matched this step name. Implement directly here.\n"
        f"# Inputs:  {', '.join(step.inputs) if step.inputs else '(none specified)'}\n"
        f"# Outputs: {', '.join(step.outputs) if step.outputs else '(none specified)'}\n"
        f"\n"
        f"def step_{step.order:02d}_{slug}():\n"
        f"    \"\"\"{step.description or step.name}\"\"\"\n"
        f"    raise NotImplementedError('TODO: implement step {step.order}')\n"
    )


# ---- Falsifiability cell ----------------------------------------------------


def _falsifiability_code(plan: ExperimentPlan) -> str:
    return (
        "# === Falsifiability check ===\n"
        f"# Primary metric: {plan.primary_metric}\n"
        f"# Success threshold: {plan.success_threshold}\n"
        f"# Null outcome:     {plan.null_outcome}\n"
        "\n"
        "try:\n"
        "    model_metric_value = float(model_auroc)\n"
        "    baseline_metric_value = float(baseline_auroc)\n"
        "except NameError:\n"
        "    model_metric_value = None\n"
        "    baseline_metric_value = None\n"
        "\n"
        "if model_metric_value is None or baseline_metric_value is None:\n"
        "    raise NotImplementedError('Run the evaluation step first, or set values manually.')\n"
        "\n"
        "lift = model_metric_value - baseline_metric_value\n"
        "print(f'primary metric (model):    {model_metric_value:.4f}')\n"
        "print(f'primary metric (baseline): {baseline_metric_value:.4f}')\n"
        "print(f'lift over baseline:        {lift:+.4f}')\n"
        "\n"
        "MIN_LIFT_FOR_HYPOTHESIS = 0.07  # TODO: align with the falsifiability threshold above\n"
        "assert lift >= MIN_LIFT_FOR_HYPOTHESIS, (\n"
        "    f'Lift {lift:+.4f} is below the falsifiability threshold {MIN_LIFT_FOR_HYPOTHESIS}. '\n"
        "    'Per the hypothesis null outcome, this run falsifies the hypothesis.'\n"
        ")\n"
        "print('falsifiability check PASSED')\n"
    )
