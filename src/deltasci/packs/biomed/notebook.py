# ---- Step routing ----------------------------------------------------------


def _step_markdown(step: ProtocolStep) -> dict:
    parts = [f"## Step {step.order}: {step.name}"]
    if step.description:
        parts.extend(["", step.description])
    if step.inputs:
        parts.extend(["", f"**Inputs:** {', '.join(step.inputs)}"])
    if step.outputs:
        parts.append(f"**Outputs:** {', '.join(step.outputs)}")
    if step.method_citations:
        parts.extend(["", "**Methods cited:**"])
        for c in step.method_citations:
            parts.append(f"- {c}")
    return markdown_cell("\n".join(parts) + "\n")


def _route_step_code(step: ProtocolStep) -> str:
    name = (step.name + " " + (step.description or "")).lower()
    if any(k in name for k in ("cohort", "assembly", "linkage", "clinical")):
        return _step_cohort(step)
    if any(k in name for k in ("qc", "quality", "filter", "preprocess")):
        return _step_qc(step)
    if any(k in name for k in ("annotation", "cell-type", "celltype", "clustering", "leiden")):
        return _step_annotation(step)
    if any(k in name for k in ("spatial", "neighbor", "graph construction")):
        return _step_spatial_graph(step)
    if any(k in name for k in ("train", "model", "fit", "encoder", "hgt", "gnn")):
        return _step_train(step)
    if any(k in name for k in ("evaluat", "metric", "calibration", "auroc", "auc", "auprc")):
        return _step_evaluate(step)
    return _step_generic(step)


